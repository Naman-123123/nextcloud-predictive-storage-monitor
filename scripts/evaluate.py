"""Evaluate the capacity predictor under different storage-usage scenarios.

For every simulated scenario the true moment the pool fills up is known. The
predictor is given only the history available at a cut-off time and its
forecast is compared with that ground truth, for several regression windows.

  python scripts/evaluate.py            # prints a table and writes docs/evaluation.md
"""
import sys
from datetime import timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "monitor"))

from app.collector import SEED_STEP, _storage_totals  # noqa: E402
from app.predictor import forecast  # noqa: E402
from app.sources.simulator import SCENARIOS, SimulatedNextcloud  # noqa: E402

CUTOFFS = [-10, -5, 0]          # days relative to "now" in the simulation
WINDOWS = [3, 7, 14, 30]        # regression window in days (30 = whole history)


def history(sim):
    t, out = sim.history_start, []
    end = sim.anchor + timedelta(days=60)
    while t <= end:
        snap = sim.snapshot(t)
        out.append((t, _storage_totals(snap, sim.capacity)["used_bytes"]))
        t += SEED_STEP
    return out


def fmt(d):
    return "never" if d is None else f"{d:.1f}"


def main():
    lines = ["| Scenario | Cut-off | Window (d) | Samples | Growth (MB/day) | R² | Predicted days to full | "
             "Actual days to full | Error (days) |",
             "|---|---|---|---|---|---|---|---|---|"]
    summary = {}
    for name in SCENARIOS:
        sim = SimulatedNextcloud(name)
        hist = history(sim)
        truth_at = sim.exhausted_at
        for c in CUTOFFS:
            cutoff = sim.anchor + timedelta(days=c)
            if truth_at and truth_at <= cutoff:
                continue
            actual = (truth_at - cutoff).total_seconds() / 86400 if truth_at else None
            for w in WINDOWS:
                recs = [(t, u) for t, u in hist if cutoff - timedelta(days=w) <= t <= cutoff]
                p = forecast(recs, sim.capacity, cutoff)
                pred = p["days_remaining"]
                if actual is not None and pred is not None:
                    err = pred - actual
                    err_s = f"{err:+.1f}"
                    summary.setdefault((SCENARIOS[name]["label"], w), []).append(abs(err))
                else:
                    err_s = "correct (no exhaustion)" if actual is None and (pred is None or pred > 60) else "n/a"
                lines.append(f"| {SCENARIOS[name]['label']} | now{c:+d} d | {w} | {p['sample_count']} | "
                             f"{p['growth_bytes_per_day'] / 1024 ** 2:.0f} | {p['r_squared'] or 0:.3f} | "
                             f"{fmt(pred)} | {fmt(actual)} | {err_s} |")

    lines += ["", "**Mean absolute error by scenario and regression window** (scenarios that do fill up):", "",
              "| Scenario | Window (days) | MAE (days) | Cases |", "|---|---|---|---|"]
    for (label, w), errs in summary.items():
        lines.append(f"| {label} | {w} | {sum(errs) / len(errs):.2f} | {len(errs)} |")

    report = "# Predictor evaluation\n\nGenerated by `scripts/evaluate.py` against the simulated scenarios " \
             "(capacity 10 GB, samples every 6 hours).\n\n" + "\n".join(lines) + "\n"
    out = ROOT / "docs" / "evaluation.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text(report, encoding="utf-8")
    print(report)
    print(f"written to {out}")


if __name__ == "__main__":
    main()
